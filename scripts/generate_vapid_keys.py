#!/usr/bin/env python3
"""
Generate a VAPID key pair for ChickCheck web push.

    .venv/bin/python scripts/generate_vapid_keys.py >> .env

Keep VAPID_PRIVATE_KEY secret: it belongs only in the backend environment,
never in frontend code or version control. Rotating it invalidates every
existing browser subscription (devices must re-enable notifications).
"""
import base64

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec


def b64url(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()


def main() -> None:
    key = ec.generate_private_key(ec.SECP256R1())
    private_raw = key.private_numbers().private_value.to_bytes(32, "big")
    public_raw = key.public_key().public_bytes(
        serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint
    )
    print("# Web push (VAPID) — generated by scripts/generate_vapid_keys.py")
    print("WEBPUSH_ENABLED=true")
    print(f"VAPID_PUBLIC_KEY={b64url(public_raw)}")
    print(f"VAPID_PRIVATE_KEY={b64url(private_raw)}")
    print("VAPID_SUBJECT=mailto:alerts@farm.local")


if __name__ == "__main__":
    main()
